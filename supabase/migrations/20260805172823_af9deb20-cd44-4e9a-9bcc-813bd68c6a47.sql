CREATE OR REPLACE VIEW public.v_user_item_implicit
WITH (security_invoker = true) AS
SELECT
  e.user_id,
  e.subject_id AS resource_id,
  ROUND(SUM(
    CASE e.event_type
      WHEN 'impression' THEN 0.1
      WHEN 'click'      THEN 1.0
      WHEN 'open'       THEN 1.5
      WHEN 'download'   THEN 3.0
      WHEN 'save'       THEN 3.0
      WHEN 'share'      THEN 3.5
      WHEN 'like'       THEN 2.5
      WHEN 'comment'    THEN 3.0
      WHEN 'rate'       THEN 4.0
      WHEN 'vote'       THEN 2.0
      WHEN 'complete'   THEN 5.0
      WHEN 'unlike'     THEN -2.5
      WHEN 'unsave'     THEN -3.0
      ELSE 0.0
    END
    * exp(-0.0077 * GREATEST(EXTRACT(EPOCH FROM (now() - e.occurred_at)) / 86400.0, 0))
  )::numeric + COALESCE(SUM(ln(1 + COALESCE(e.dwell_ms, 0) / 1000.0)), 0)::numeric, 4) AS score,
  COUNT(*) AS event_count,
  MAX(e.occurred_at) AS last_seen_at
FROM public.interaction_events e
WHERE e.subject_type = 'resource' AND e.subject_id IS NOT NULL
GROUP BY e.user_id, e.subject_id;

CREATE OR REPLACE VIEW public.v_session_sequences
WITH (security_invoker = true) AS
SELECT
  e.user_id,
  e.session_id,
  MIN(e.occurred_at) AS started_at,
  MAX(e.occurred_at) AS ended_at,
  COUNT(*) AS event_count,
  SUM(COALESCE(e.dwell_ms, 0)) AS total_dwell_ms,
  ARRAY_AGG(e.subject_id ORDER BY e.sequence_no NULLS LAST, e.occurred_at) AS subject_path,
  ARRAY_AGG(e.event_type::text ORDER BY e.sequence_no NULLS LAST, e.occurred_at) AS verb_path,
  ARRAY_AGG(COALESCE(e.surface, '') ORDER BY e.sequence_no NULLS LAST, e.occurred_at) AS surface_path
FROM public.interaction_events e
WHERE e.session_id IS NOT NULL
GROUP BY e.user_id, e.session_id;

CREATE OR REPLACE VIEW public.v_resource_features
WITH (security_invoker = true) AS
SELECT
  r.id AS resource_id,
  r.title, r.description, r.link, r.provider,
  r.resource_type, r.section_type,
  r.domain, r.subdomain, r.category,
  r.difficulty, r.language, r.duration, r.estimated_time,
  r.is_free, r.is_featured, r.is_active, r.created_at,
  COALESCE(ARRAY(
    SELECT rs.skill_name FROM public.resource_skills rs WHERE rs.resource_id = r.id ORDER BY rs.skill_name
  ), '{}') AS skills,
  st.avg_rating, st.weighted_rating, st.total_ratings,
  st.recommend_percent, st.total_votes, st.total_reviews,
  st.view_count, st.click_count, st.total_dwell_ms
FROM public.resources r
LEFT JOIN public.resource_stats st ON st.resource_id = r.id;

