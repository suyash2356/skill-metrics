CREATE TYPE public.interaction_subject AS ENUM
  ('resource','post','roadmap','skill','profile','search','user_resource');

CREATE TYPE public.interaction_verb AS ENUM
  ('impression','click','open','dwell','download','like','unlike','save','unsave',
   'share','comment','rate','vote','complete','search');

CREATE TABLE public.interaction_events (
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id       uuid NOT NULL,
  session_id    uuid,
  subject_type  public.interaction_subject NOT NULL,
  subject_id    uuid,
  event_type    public.interaction_verb NOT NULL,
  dwell_ms      integer,
  position      integer,
  surface       text,
  variant       text,
  model_version text,
  sequence_no   integer,
  context       jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at   timestamptz NOT NULL DEFAULT now(),
  created_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id, occurred_at),
  CONSTRAINT interaction_events_dwell_sane CHECK (dwell_ms IS NULL OR (dwell_ms >= 0 AND dwell_ms <= 1800000))
) PARTITION BY RANGE (occurred_at);

-- history partition (all pre-existing backfilled data) + rolling monthly partitions
CREATE TABLE public.interaction_events_history PARTITION OF public.interaction_events
  FOR VALUES FROM (MINVALUE) TO ('2026-08-01');

DO $$
DECLARE
  m date := date_trunc('month', now())::date;
  i integer;
BEGIN
  FOR i IN 0..14 LOOP
    EXECUTE format(
      'CREATE TABLE IF NOT EXISTS public.interaction_events_%s PARTITION OF public.interaction_events FOR VALUES FROM (%L) TO (%L)',
      to_char(m + (i || ' month')::interval, 'YYYY_MM'),
      (m + (i || ' month')::interval)::date,
      (m + ((i + 1) || ' month')::interval)::date
    );
  END LOOP;
END $$;

CREATE TABLE public.interaction_events_future PARTITION OF public.interaction_events DEFAULT;

CREATE INDEX idx_ie_user_time    ON public.interaction_events (user_id, occurred_at DESC);
CREATE INDEX idx_ie_subject      ON public.interaction_events (subject_type, subject_id, event_type);
CREATE INDEX idx_ie_session_seq  ON public.interaction_events (session_id, sequence_no);
CREATE INDEX idx_ie_verb_time    ON public.interaction_events (event_type, occurred_at DESC);
CREATE INDEX idx_ie_occurred_brin ON public.interaction_events USING brin (occurred_at);

GRANT SELECT, INSERT ON public.interaction_events TO authenticated;
GRANT ALL ON public.interaction_events TO service_role;
ALTER TABLE public.interaction_events ENABLE ROW LEVEL SECURITY;

