CREATE OR REPLACE VIEW public.v_recommendation_outcomes
WITH (security_invoker = true) AS
SELECT
  imp.user_id,
  imp.subject_id AS resource_id,
  imp.surface,
  imp.variant,
  imp.model_version,
  imp.position,
  imp.occurred_at AS impressed_at,
  EXISTS (
    SELECT 1 FROM public.interaction_events c
    WHERE c.user_id = imp.user_id
      AND c.subject_id = imp.subject_id
      AND c.event_type IN ('click','open','save','download','complete')
      AND c.occurred_at BETWEEN imp.occurred_at AND imp.occurred_at + interval '1 hour'
  ) AS converted
FROM public.interaction_events imp
WHERE imp.event_type = 'impression' AND imp.subject_type = 'resource';

GRANT SELECT ON public.v_recommendation_outcomes TO authenticated, service_role;

